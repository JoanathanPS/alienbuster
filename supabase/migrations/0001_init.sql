-- Allow authenticated users to insert reports where auth.uid() equals user_id
create policy "Allow insert by authenticated user" on public.reports
  for insert
  with check (auth.uid() = user_id);

-- Allow select on reports to authenticated users (or tune fields returned)
create policy "Allow select to authenticated" on public.reports
  for select using (auth.role() IS NOT NULL);

-- Allow admins (user_roles.role = 'admin') to update critical fields
create policy "Allow admin update" on public.reports
  for update using (public.has_role('admin'::public.app_role, auth.uid()))
  with check (public.has_role('admin'::public.app_role, auth.uid()));

