-- Supabase migration: initial schema for Alien Buster
-- Run this in the Supabase SQL editor or as a migration.

-- Enable pgcrypto for gen_random_uuid()
create extension if not exists "pgcrypto";

-- Roles enum
create type public.app_role as enum ('admin','user');

-- user_roles
create table public.user_roles (
  id text primary key default gen_random_uuid()::text,
  user_id text not null,
  role public.app_role not null,
  created_at timestamptz default now()
);
create index if not exists user_roles_user_id_idx on public.user_roles(user_id);
create index if not exists user_roles_role_idx on public.user_roles(role);

-- reports (main user-submitted sightings)
create table public.reports (
  id bigint generated by default as identity primary key,
  created_at timestamptz default now() not null,
  user_id text not null,
  user_email text,
  reporter_nickname text,
  latitude double precision not null,
  longitude double precision not null,
  species text,
  ml_confidence real,
  is_invasive boolean,
  photo_path text,
  photo_url text,
  notes text,
  description text,
  topk jsonb,
  status text default 'unverified',
  ndvi_recent real,
  ndvi_baseline real,
  ndvi_change real,
  ndvi_anomaly boolean,
  landcover_recent_json jsonb,
  landcover_baseline_json jsonb,
  landcover_shift real,
  report_density real,
  satellite_score real,
  fused_risk real,
  photo_quality real,
  recommended_action text,
  fused_components_json jsonb,
  fused_reasons_json jsonb,
  needs_more_info_message text,
  needs_more_info_requested_photos_json jsonb,
  inat_id bigint,
  constraint reports_inat_id_unique unique (inat_id)
);
create index if not exists reports_created_at_idx on public.reports (created_at);
create index if not exists reports_status_idx on public.reports (status);
create index if not exists reports_lat_lon_idx on public.reports (latitude, longitude);
create index if not exists reports_species_idx on public.reports (species);
create index if not exists reports_is_invasive_idx on public.reports (is_invasive);

-- validations
create table public.validations (
  id bigint generated by default as identity primary key,
  created_at timestamptz default now() not null,
  report_id bigint not null references public.reports(id) on delete cascade,
  reviewer text,
  expert_email text,
  decision text not null,
  confidence real,
  confidence_override real,
  notes text
);
create index if not exists validations_report_idx on public.validations(report_id);
create index if not exists validations_created_at_idx on public.validations(created_at);

-- experts
create table public.experts (
  email text primary key,
  name text,
  created_at timestamptz default now() not null
);

-- reporters (reputation)
create table public.reporters (
  user_id text primary key,
  reputation real default 0.5
);

-- species_verifications
create table public.species_verifications (
  id bigint generated by default as identity primary key,
  species text not null,
  latitude double precision not null,
  longitude double precision not null,
  verified_at timestamptz not null default now(),
  verified_by text not null,
  evidence_report_id bigint references public.reports(id),
  confidence real,
  notes text
);
create index if not exists species_verifications_species_idx on public.species_verifications(species);
create index if not exists species_verifications_verified_at_idx on public.species_verifications(verified_at);

-- confusion_cases
create table public.confusion_cases (
  id bigint generated by default as identity primary key,
  created_at timestamptz default now() not null,
  report_id bigint references public.reports(id),
  predicted_species text,
  predicted_confidence real,
  expert_decision text
);
create index if not exists confusion_cases_created_at_idx on public.confusion_cases(created_at);

-- feedback
create table public.feedback (
  id bigint generated by default as identity primary key,
  created_at timestamptz default now() not null,
  report_id bigint references public.reports(id),
  user_id text,
  species text,
  was_correct boolean,
  notes text
);
create index if not exists feedback_created_at_idx on public.feedback(created_at);

-- outbreaks
create table public.outbreaks (
  id bigint generated by default as identity primary key,
  species text not null,
  created_at timestamptz default now() not null,
  updated_at timestamptz default now() not null,
  centroid_lat double precision not null,
  centroid_lon double precision not null,
  radius_km double precision not null,
  num_reports integer not null,
  mean_risk real not null,
  ndvi_anomaly_rate real not null,
  status text not null
);
create index if not exists outbreaks_species_idx on public.outbreaks(species);
create index if not exists outbreaks_status_idx on public.outbreaks(status);
create index if not exists outbreaks_updated_at_idx on public.outbreaks(updated_at);

-- tasks
create table public.tasks (
  id bigint generated by default as identity primary key,
  outbreak_id bigint references public.outbreaks(id),
  report_id bigint references public.reports(id),
  assigned_to text,
  agency text,
  priority text not null,
  status text not null,
  due_at timestamptz,
  created_at timestamptz default now() not null,
  notes text
);
create index if not exists tasks_status_idx on public.tasks(status);
create index if not exists tasks_priority_idx on public.tasks(priority);
create index if not exists tasks_created_at_idx on public.tasks(created_at);

-- has_role function (user_id as text)
create function public.has_role(_role public.app_role, _user_id text) returns boolean
  language sql stable as $$
    select exists(select 1 from public.user_roles ur where ur.user_id = _user_id and ur.role = _role);
  $$;

